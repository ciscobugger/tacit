#!/usr/bin/env python3
# argparse, os, re and tempfile only: no virtualenv needed, and the shell runs this with
# `python3 <path>` anyway. The old shebang sourced a venv through /bin/sh, which is dash on
# most distros and has no `source`.
import argparse
import os
import re
import tempfile

BOOL_KEYS = {
    "decoration:blur:enabled",
    "decoration:shadow:enabled",
    "animations:enabled",
    "general:allow_tearing",
    "input:numlock_by_default",
    "input:touchpad:natural_scroll",
    "input:touchpad:disable_while_typing",
    "input:touchpad:clickfinger_behavior",
    "input:touchpad:tap_to_click",
}

FALSE_VALUES = {"0", "0.0", "false", "False", "no", ""}



def to_lua_value(key, value):
    if key in BOOL_KEYS:
        # Callers pass 1/0, but a model-driven toggle forwards the bool itself
        # (HyprlandConfigOption.qml), and "false" used to come out as true.
        return "false" if value.strip() in FALSE_VALUES else "true"
    try:
        return str(int(value))
    except ValueError:
        pass
    try:
        return str(float(value))
    except ValueError:
        pass
    return f'"{value}"'


# "device:<name>:<option>": one option of one input device (Hyprland's hl.device), e.g. a touchpad's own speed. The name
# can hold colons itself ("hid-over-i2c-14e5:650e-touchpad"); the option is after the last one.
def device_key(key):
    if not key.startswith("device:"):
        return None
    name, _, option = key[len("device:"):].rpartition(":")
    return name, option


def to_lua_line(key, value):
    dev = device_key(key)
    if dev:
        return f'hl.device({{ name = "{dev[0]}", {dev[1]} = {to_lua_value(dev[1], value)} }})\n'
    parts = key.replace(":", ".").split(".")
    val = to_lua_value(key, value)
    inner = f"{{ {parts[-1]} = {val} }}"
    for part in reversed(parts[:-1]):
        inner = f"{{ {part} = {inner} }}"
    return f"hl.config({inner})\n"


def make_marker(key):
    dev = device_key(key)
    if dev:
        return f'hl.device({{ name = "{dev[0]}", {dev[1]} ='
    parts = key.replace(":", ".").split(".")

    fragment = " = { ".join(parts[:-1])
    if fragment:
        fragment += " = { " + parts[-1] + " ="
    else:
        fragment = parts[-1] + " ="
    return fragment


def write_atomic(path, content):
    dir_name = os.path.dirname(os.path.abspath(path))
    os.makedirs(dir_name, exist_ok=True)
    tmp_path = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", dir=dir_name, delete=False) as f:
            f.write(content)
            tmp_path = f.name
        if os.path.exists(path):
            os.chmod(tmp_path, os.stat(path).st_mode)
        os.replace(tmp_path, path)
    except Exception as e:
        if tmp_path and os.path.exists(tmp_path):
            os.remove(tmp_path)
        raise e


# The per-device pointer profiles (Settings > Touchpad and > Mouse), said to the hotplug layer in
# tacit/general.lua, which hands a pointer its class's resolution when one is plugged in: a
# shellOverrides file of one Lua table, written alongside main.lua. Every device the Settings knows
# sits here with its accel_profile as it was written (a curve named "accel" itself, or "flat",
# "adaptive", with libinput's speed beside it).
def devices_file_for(file_path):
    return os.path.join(os.path.dirname(file_path), "devices.lua")


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_unquote(text):
    """The inside of a string lua_string wrote, back to the text."""
    return re.sub(r"\\(.)", r"\1", text)


def read_devices(path):
    try:
        with open(path) as f:
            text = f.read()
    except FileNotFoundError:
        return {}
    entries = {}
    # every entry was written by this script as one line: ["name"] = { accel = "...", speed = 0.5 },
    # so the order and words are ours and a plain read is safe
    for m in re.finditer(r'\["((?:[^"\\]|\\.)+)"\]\s*=\s*\{([^}]*)\}', text):
        fields = dict(re.findall(r'(\w+)\s*=\s*("(?:[^"\\]|\\.)*"|[-0-9.]+)', m.group(2)))
        if "accel" not in fields:
            continue
        entry = {"accel": lua_unquote(fields["accel"][1:-1])}
        if "speed" in fields:
            try:
                entry["speed"] = float(fields["speed"])
            except ValueError:
                pass
        entries[lua_unquote(m.group(1))] = entry
    return entries


def write_devices(path, entries):
    lines = ["-- Generated by the shell's hyprconfigurator.py: the per-device pointer profiles,",
             "-- read by tacit/general.lua to hand a pointer its profile when one is plugged in."]
    for name, v in entries.items():
        line = f'    [{lua_string(name)}] = {{ accel = {lua_string(v["accel"])}'
        if "speed" in v:
            line += f', speed = {v["speed"]}'
        lines.append(line + " },")
    content = "return {\n" + "\n".join(lines) + "\n" + "}\n"
    write_atomic(path, content)


def edit_lua(file_path, set_pairs, reset_keys):
    try:
        with open(file_path) as f:
            lines = f.readlines()
    except FileNotFoundError:
        lines = []

    set_dict   = dict(set_pairs)
    reset_set  = set(reset_keys)
    all_keys   = list(set_dict) + list(reset_set)
    markers    = {k: make_marker(k) for k in all_keys}

    new_lines  = []
    found_keys = set()

    for line in lines:
        matched = None
        for k in all_keys:
            if markers[k] in line:
                matched = k
                break
        if matched is None:
            new_lines.append(line)
        elif matched in reset_set:
            print(f"Removed: {matched}")
        else:
            new_lines.append(to_lua_line(matched, set_dict[matched]))
            found_keys.add(matched)
            print(f"Updated: {to_lua_line(matched, set_dict[matched]).strip()}")

    for k, v in set_dict.items():
        if k not in found_keys:
            new_lines.append(to_lua_line(k, v))
            print(f"Added:   {to_lua_line(k, v).strip()}")

    write_atomic(file_path, "".join(new_lines))


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--file", default="~/.config/hypr/hyprland/shellOverrides/main.lua")
    p.add_argument("--set", nargs=2, action="append", metavar=("KEY", "VALUE"))
    p.add_argument("--reset", action="append", metavar="KEY")
    args = p.parse_args()

    raw_sets   = args.set or []
    reset_keys = args.reset or []
    set_pairs  = []
    for k, v in raw_sets:
        if v == "[[EMPTY]]":
            reset_keys.append(k)
        else:
            set_pairs.append((k, v))

    if set_pairs or reset_keys:
        file_path = os.path.expanduser(args.file)

        # the same run brings the per-device resolutions to the hotplug layer: the device's accel_profile
        # as it was written, with libinput's speed beside it when it is not a curve
        devices_path = devices_file_for(file_path)
        devices = read_devices(devices_path)
        changed = False
        for k, v in set_pairs:
            dev = device_key(k)
            if not dev:
                continue
            name, option = dev
            if option == "accel_profile":
                if devices.get(name, {}).get("accel") != v:
                    devices[name] = {"accel": v}
                    changed = True
            elif option == "sensitivity" and name in devices:
                try:
                    speed = float(v)
                except ValueError:
                    continue
                if devices[name].get("speed") != speed:
                    devices[name]["speed"] = speed
                    changed = True
        for k in reset_keys:
            dev = device_key(k)
            if not dev:
                continue
            name, option = dev
            if option == "accel_profile":
                if name in devices:
                    del devices[name]
                    changed = True
            elif option == "sensitivity":
                if name in devices and "speed" in devices[name]:
                    del devices[name]["speed"]
                    changed = True
        # before main.lua: its edit makes Hyprland reload, and the reload's hotplug layer reads this file
        if changed:
            write_devices(devices_path, devices)
        edit_lua(file_path, set_pairs, reset_keys)
    else:
        print("Error: specify --set or --reset")