-- Quickshell
-- Quickshell: illogical-impulse
hl.layer_rule({ match = { namespace = "quickshell:.*" }, blur_popups = true})
hl.layer_rule({ match = { namespace = "quickshell:.*" }, blur = true})
hl.layer_rule({ match = { namespace = "quickshell:.*" }, ignore_alpha = 0.79})
-- The catch-all above blurs EVERY quickshell layer at 3 passes. Three of them can
-- never benefit: the wallpaper is the bottom-most layer with nothing behind it, and
-- the frame and corners are small opaque decorations. Blurring a fullscreen
-- 1920x1080 surface every frame is the most expensive thing the compositor was
-- doing, for no visible result. NOTE: the field is `blur`, not `no_blur` - no_blur
-- is a WINDOW rule only, and using it here raises "unknown field", which aborts this
-- module and (before safe_require) unregistered every keybind.
hl.layer_rule({ match = { namespace = "quickshell:background" }, blur = false})
hl.layer_rule({ match = { namespace = "quickshell:screenframe" }, blur = false})
hl.layer_rule({ match = { namespace = "quickshell:screenCorners" }, blur = false})
hl.layer_rule({ match = { namespace = "quickshell:bar" }, animation = "slide"})
hl.layer_rule({ match = { namespace = "quickshell:dock" }, animation = "slide bottom"})
-- the corners are two screen-wide strips (ScreenCorners.qml): a pop-in from 120 % slid them in from far off-screen
hl.layer_rule({ match = { namespace = "quickshell:screenCorners" }, animation = "fade"})
-- made when something shows and gone after (NotificationPopup.qml): the panel unfolds and folds itself, as it did when
-- the window was always there
hl.layer_rule({ match = { namespace = "quickshell:notificationPopup" }, no_anim = true})
hl.layer_rule({ match = { namespace = "quickshell:overlay" }, no_anim = true})
hl.layer_rule({ match = { namespace = "quickshell:overlay" }, ignore_alpha = 1})
