-- put former exec-once commands inside the func and former exec commands outside
hl.on("hyprland.start", function ()

    -- Tacit's places (hyprland/env.lua) for the user services and D-Bus activated programs, which do not inherit
    -- Hyprland's environment: the session's services, the shell's helpers and the screen share portal need them.
    hl.exec_cmd("systemctl --user import-environment TACIT_SHELL TACIT_BIN TACIT_HYPR XDG_CONFIG_DIRS PATH; dbus-update-activation-environment --systemd TACIT_SHELL TACIT_BIN TACIT_HYPR XDG_CONFIG_DIRS PATH")

    -- Bar, wallpaper
    -- Boot lock FIRST, as the compositor's first client: a second, tiny quickshell instance
    -- that runs only the shell's lock surface (bootlock.qml: same ground, discs, hover), up
    -- in well under a second, so nothing else (wallpaper, panels, the shell's 15s startup)
    -- can show before the lock. hyprlock only if that fails to start; if both fail the
    -- desktop simply appears (allow_session_lock_restore is on). The fallback keys off the
    -- ready marker, not the exit code: the boot lock ends itself with a signal after unlock.
    -- The ground first: the compositor's own first frames already paint it (wall0.png link),
    -- swaybg keeps it up until the lock, and the splash daemon hands over with a page flip
    -- (its mode-set mirrors aquamarine's, identity CTM included), so nothing goes dark.
    -- The boot still (tacit-boot-ground) under everything until the shell's wallpaper is up; it only exists once the
    -- person's boot pictures have been made, and without the test swaybg dies on a missing file and says nothing.
    hl.exec_cmd("bash -c 'g=${XDG_STATE_HOME:-$HOME/.local/state}/tacit-boot/still.png; command -v swaybg >/dev/null && [ -f $g ] && exec swaybg -m fill -i $g'")
    -- session_lock_xray only while the boot lock draws its first frame: the compositor blacks the screen out from the
    -- lock request to the lock's first frame, and with xray it shows what is underneath instead (the boot still, the same
    -- pixels). bootlock.qml switches it off once its sky is under way, and this line again when the boot lock ends.
    -- Not on Tacit's live system (/run/archiso): its user has no password and goes straight to Setup.
    -- Not after a sign-in at the login screen either (logind's Service "sddm", not "sddm-autologin"): the password was
    -- just typed there, and the boot lock asked for it a second time; the ready marker says someone has signed in.
    hl.exec_cmd("bash -c '[ -d /run/archiso ] && exit 0; [ \"$(loginctl show-session \"$XDG_SESSION_ID\" -p Service --value 2>/dev/null)\" = sddm ] && { touch $XDG_RUNTIME_DIR/martida-lock-ready; exit 0; }; rm -f $XDG_RUNTIME_DIR/martida-lock-ready; hyprctl eval \"hl.config({ misc = { session_lock_xray = true } })\" >/dev/null 2>&1; QS_BOOTLOCK=1 qs -p $TACIT_SHELL/bootlock.qml; hyprctl eval \"hl.config({ misc = { session_lock_xray = false } })\" >/dev/null 2>&1; [ -e $XDG_RUNTIME_DIR/martida-lock-ready ] || { hyprlock --immediate-render --no-fade-in & sleep 0.5; touch $XDG_RUNTIME_DIR/martida-lock-ready; wait; }'")
    hl.exec_cmd("$TACIT_HYPR/hyprland/scripts/start_geoclue_agent.sh")
    -- Unsupervised is the fallback, not the plan: say so instead of leaving ~/.cache/qs-startup.log
    -- as the only trace that the crash-loop backoff and its give-up note are absent.
    hl.exec_cmd("bash -c 'if [ -x $TACIT_BIN/qs-supervise ]; then exec $TACIT_BIN/qs-supervise; fi; hyprctl notify -1 10000 \"rgb(ffaa55)\" \"qs-supervise is missing - the shell runs unsupervised\"; qs -p $TACIT_SHELL > $HOME/.cache/qs-startup.log 2>&1'")
    -- Book4-only, and 15s of sleep plus ~30 hyprctl/wpctl/journalctl calls at every login:
    -- armed by hand, the way charge-monitor's dump is. touch ~/.cache/hypr-diag/ARM for it.
    hl.exec_cmd("bash -c '[ -e $HOME/.cache/hypr-diag/ARM ] && [ -x $HOME/.local/bin/book4-hypr-diag.sh ] && exec $HOME/.local/bin/book4-hypr-diag.sh'")
    -- Generated by switchwall.sh: it holds nothing but a comment until a video wallpaper is set,
    -- and it is not executable until then either.
    hl.exec_cmd("bash -c 'v=$HOME/.config/hypr/custom/scripts/__restore_video_wallpaper.sh; [ -x $v ] && exec $v'")

    -- Core components (authentication, lock screen, notification daemon)
    -- not on Tacit's live system (/run/archiso): its idle lock would shut Setup behind a lock its user has no password
    -- for, and its sleep stopped installs (the VM test, 2026-10-16: asleep at 15 minutes on Setup's last page)
    hl.exec_cmd("bash -c '[ -d /run/archiso ] || exec hypridle'")
    -- Documents, Pictures, Downloads, Music, Videos in the person's language, made if missing: xdg-user-dirs.service
    -- waits on graphical-session-pre.target, which this session never starts, so a new account had none of them
    hl.exec_cmd("xdg-user-dirs-update")
    -- phone bridge, daemon only; the shell shows its notifications. kdeconnect is not a dependency (Tacit runs without
    -- a phone), so only start it when it is installed: an unguarded exec is a failed command at every login.
    hl.exec_cmd("bash -c 'command -v kdeconnectd >/dev/null && exec kdeconnectd'")
    hl.exec_cmd("dbus-update-activation-environment --all")
    -- Hyprland is not started by a systemd session generator, so nothing ever reaches
    -- graphical-session.target, which refuses a manual start. Three of this desktop's own
    -- units were WantedBy it (flowd, focus-priority, cma-watch) and so never ran at all.
    -- They are wanted by tacit-session.target now; start it after the activation
    -- environment is exported so the units inherit WAYLAND_DISPLAY.
    hl.exec_cmd("systemctl --user start tacit-session.target")
    hl.exec_cmd("sleep 1 && dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP") -- Some fix idk

    -- Audio

    -- Clipboard: history
    --hl.exec_cmd("wl-paste --watch cliphist store")
    hl.exec_cmd("wl-paste --type text --watch bash -c 'cliphist store && qs -p $TACIT_SHELL ipc call cliphistService update'")
    hl.exec_cmd("wl-paste --type image --watch bash -c 'cliphist store && qs -p $TACIT_SHELL ipc call cliphistService update'")

    -- Cursor
    -- the size Tacit Settings chose (it writes gsettings cursor-size)
    hl.exec_cmd("bash -c 'hyprctl setcursor Tacit $(gsettings get org.gnome.desktop.interface cursor-size 2>/dev/null || echo 24)'")
end)
